const uint8_t *font_get_glyph(char c)
{
    if (c < FONT_FIRST_CHAR || c > FONT_LAST_CHAR) {
        return NULL;
    }
    return font_8x8[c - FONT_FIRST_CHAR];
}

int font_render_char(uint8_t *buf, size_t buf_size, char c, uint16_t x, uint8_t page)
{
    const uint8_t *glyph;
    uint8_t i, j;

    if (buf == NULL || buf_size == 0) {
        return -1;
    }

    glyph = font_get_glyph(c);
    if (glyph == NULL) {
        return -1;
    }

    if (x + FONT_WIDTH > FONT_DISPLAY_WIDTH) {
        return -1;
    }

    for (i = 0; i < 8; i++) {
        for (j = 0; j < 8; j++) {
            if (glyph[i] & (0x80 >> j)) {
                uint16_t col = x + j;
                uint16_t idx = (uint16_t)page * 128 + col;
                if (idx < buf_size) {
                    buf[idx] |= (1 << i);
                }
            }
        }
    }

    return 0;
}

int font_render_text(uint8_t *buf, size_t buf_size, const char *text, uint16_t x, uint8_t page)
{
    int ret = 0;

    while (*text != '\0') {
        ret = font_render_char(buf, buf_size, *text, x, page);
        if (ret < 0) {
            return ret;
        }
        x += FONT_WIDTH;
        text++;
    }

    return 0;
}

bool font_is_printable(char c)
{
    return (c >= FONT_FIRST_CHAR && c <= FONT_LAST_CHAR);
}