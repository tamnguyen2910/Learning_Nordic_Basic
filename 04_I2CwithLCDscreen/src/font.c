const uint8_t *font_get_glyph(char c)
{
    if (c < FONT_FIRST_CHAR || c > FONT_LAST_CHAR) {
        return NULL;
    }
    return font_8x8[c - FONT_FIRST_CHAR];
}

int font_render_char(uint8_t *buf, size_t buf_size, char c, uint16_t x, uint8_t y)
{
    const uint8_t *glyph;
    uint8_t i, j;

    if (buf == NULL || buf_size == 0) {
        return -1;
    }

    glyph = font_get_glyph(c);
    if (glyph == NULL) {
        return -1;
    }

    /* Check if character fits within display width */
    if (x + FONT_WIDTH > FONT_DISPLAY_WIDTH) {
        return -1;
    }

    /* SSD1306 memory layout: 8 pages, 128 bytes per page
     * Each byte represents 8 vertical pixels at one column
     * Page y covers rows y*8 to y*8+7
     * Buffer index: page * 128 + column
     *
     * Font is 8x8 pixels. For each pixel in glyph:
     * - glyph[i] contains row i (8 horizontal pixels, bit 0 = leftmost)
     * - pixel (bit_j, row_i) maps to buffer[page, column = x + j]
     *   where page = y (each glyph row spans 8 vertical pixels = 1 page)
     *   and bit position = i (0-7 within the byte)
     */

    for (i = 0; i < 8; i++) {
        /* Each glyph byte represents one row of 8 pixels
         * Font data uses MSB = leftmost pixel (bit 7 = col x+0, bit 0 = col x+7)
         */
        for (j = 0; j < 8; j++) {
            if (glyph[i] & (0x80 >> j)) {
                /* Bit (7-j) is set in row i of the glyph
                 * This pixel goes to:
                 *   - Page: y (since each glyph row = 8 vertical pixels = 1 page)
                 *   - Column: x + j
                 *   - Bit position: i (0-7, vertical position within the byte)
                 */
                uint16_t col = x + j;
                uint16_t byte_idx = (uint16_t)y * 128 + col;

                if (byte_idx < buf_size) {
                    buf[byte_idx] |= (1 << i);
                }
            }
        }
    }

    return 0;
}

bool font_is_printable(char c)
{
    return (c >= FONT_FIRST_CHAR && c <= FONT_LAST_CHAR);
}
